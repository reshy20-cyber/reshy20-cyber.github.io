#!/usr/bin/env python3
"""Builds Tafawoq Prep (تفوق إعدادي) from the Tafawoq secondary app's engine.

  python3 build.py <path to tafawoq/index.html> <path to tafawoq/sw.js>

The secondary app's content block (SUBJECTS … NOTES) is replaced with the prep content below,
and the branding, storage keys, offline cache name and Google Play product are switched to the
prep app, so the two apps can live side by side on reshy20-cyber.github.io without sharing data.
Writes ../../tafawoq-prep/index.html and sw.js.
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'tafawoq-prep')
src = open(sys.argv[1], encoding='utf-8').read()
sw = open(sys.argv[2], encoding='utf-8').read()

SUBJ = {  # id: (name, glyph, colour, unit word, unit plural)
    'arabic': ('اللغة العربية', 'ع', '#b5523b', 'الوحدة', 'وحدات'),
    'english': ('اللغة الإنجليزية', 'E', '#6b5bb5', 'الوحدة', 'وحدات'),
    'math': ('الرياضيات', '∑', '#3c5fc4', 'الوحدة', 'وحدات'),
    'science': ('العلوم', 'ع', '#2f8a4e', 'الوحدة', 'وحدات'),
    'social': ('الدراسات الاجتماعية', 'د', '#8f5a2e', 'الوحدة', 'وحدات'),
}
SUBJ['science'] = ('العلوم', '⚗', '#2f8a4e', 'الوحدة', 'وحدات')
BYNAME = {v[0]: k for k, v in SUBJ.items()}
# Content per subject comes from content/<id>.json, written from the Ministry's 2026–2027
# 3rd-preparatory term-1 textbooks: {"chapters": [...], "lessons": [...], "bank": [{ch,q,a,e}]}
# with a[0] the correct answer (the engine shuffles options at exam time).
CHAPTERS, LESSONS, bank = {}, {}, {}
for k in SUBJ:
    c = json.load(open(os.path.join(HERE, 'content', k + '.json'), encoding='utf-8'))
    CHAPTERS[k] = c['chapters']
    LESSONS[k] = c['lessons']
    assert len(c['lessons']) == len(c['chapters']), k
    bank[k] = []
    for q in c['bank']:
        assert 0 <= q['ch'] < len(c['chapters']) and len(q['a']) == 4 and len(set(q['a'])) == 4, (k, q['q'])
        a = q['a']
        if k in ('math', 'science'):  # typeset non-ASCII symbol options (−, ∅, √, ×) as LTR maths; pure ASCII is already shown LTR
            a = [x if '`' in x or x.isascii() or re.search('[\u0600-\u06ff]', x) else '`' + x + '`' for x in a]
        bank[k].append({'q': q['q'], 'a': a, 'e': q.get('e', ''), 'ch': q['ch']})

# The smart tutor searches NOTES: one note per bullet of every unit summary, titled by its topic.
def lesson_notes(subject, chapters, lessons):
    out = []
    for k, text in enumerate(lessons):
        cur = None
        for line in text.split('\n'):
            st = line.strip()
            head0 = st.split(':', 1)[0]
            starts = st.startswith('- ') or (not line.startswith(' ') and ':' in st[:40] and head0 not in ('Example', 'Examples', 'Form', 'مثال'))
            if starts or cur is None:
                if cur: out.append(cur)
                body = st[2:] if st.startswith('- ') else st
                head, sep, rest = body.partition(':')
                title = head.strip() if sep and len(head) <= 40 else chapters[k]
                cur = {'t': title + ' — ' + chapters[k] if title != chapters[k] else title, 'b': body}
            else:
                cur['b'] += '\n' + line
        if cur: out.append(cur)
    return out
NOTES = {k: lesson_notes(k, CHAPTERS[k], LESSONS[k]) for k in SUBJ}

J = lambda o: json.dumps(o, ensure_ascii=False)
data = (
    "/* ===== Tafawoq Prep content (generated by tools/tafawoq-prep/build.py). a[0] is the correct answer; options are shuffled at exam time. ===== */\n"
    "const SUBJECTS=" + J({k: {'name': v[0], 'glyph': v[1], 'color': v[2]} for k, v in SUBJ.items()}) + ";\n"
    "const BRANCHES=" + J({'prep': {'name': 'الصف الثالث الإعدادي', 'subjects': list(SUBJ)}}) + ";\n"
    "const CHAPTER_WORD=" + J({k: v[3] for k, v in SUBJ.items()}) + ";\n"
    "const CHAPTER_PLURAL=" + J({k: v[4] for k, v in SUBJ.items()}) + ";\n"
    "const chPlural=s=>CHAPTER_PLURAL[s]||'وحدات';\n"
    "const chSingle=s=>(CHAPTER_WORD[s]||'الوحدة').replace(/^ال/,'');\n"
    "const CHAPTERS=" + J(CHAPTERS) + ";\n"
    "const BANK=" + J(bank) + ";\n"
    "const PHYSICS_LESSONS=[];\nconst FIGS={};\nconst LESSONS=" + J(LESSONS) + ";\nconst ESSAYS={};\n"
    "const NOTES=" + J(NOTES) + ";\n\n"
)

a = src.index('/* ===== Tafawoq content data')
b = src.rindex('/*', 0, src.index('const MSUB'))
out = src[:a] + data + src[b:]

def rep(old, new, n=1):
    global out
    assert old in out, old[:80]
    out = out.replace(old, new) if n == 0 else out.replace(old, new, n)

rep('<title>تفوق</title>', '<title>تفوق إعدادي</title>')
rep("مساعدك للثانوية العامة المصرية", "مساعدك للشهادة الإعدادية المصرية", 0)
rep('<div class="sub">الصف الثالث الثانوي • ${esc(BRANCHES[state.branch].name)}</div>', '<div class="sub">الصف الثالث الإعدادي • 2026–2027</div>')
rep('<h1>تفوق</h1>', '<h1>تفوق <small style="font-size:.55em;opacity:.85">إعدادي</small></h1>')
rep('<div class="seg" role="group" aria-label="اختر شعبتك">', '<div class="seg" role="group" aria-label="اختر شعبتك" style="${Object.keys(BRANCHES).length>1?\'\':\'display:none\'}">')
rep("if(!BRANCHES[state.branch])state.branch='science';", "if(!BRANCHES[state.branch])state.branch=Object.keys(BRANCHES)[0];")
rep("branchSubjects().find(x=>x==='physics')||branchSubjects()[2]", "branchSubjects().find(x=>x==='physics')||branchSubjects()[0]")
rep("localStorage.getItem('tafawoq_'", "localStorage.getItem('tafawoqprep_'", 0)
rep("localStorage.setItem('tafawoq_'", "localStorage.setItem('tafawoqprep_'", 0)
rep("'tafawoq_preview'", "'tafawoqprep_preview'", 0)
rep("const PLUS_SKU='tafawoq_plus_2026_2027'", "const PLUS_SKU='tafawoq_prep_plus_2026_2027'")
rep("PLAY_ID='app.tafawoq'", "PLAY_ID='app.tafawoq.prep'")
rep('الشراء متاح من تطبيق «تفوق» على Google Play', 'الشراء متاح من تطبيق «تفوق إعدادي» على Google Play', 0)
# the secondary app's note already says the content follows the 2026–2027 ministry books; keep it.
# prep colours: purple with teal (from the TAFAWOQ PREP design)
rep('--accent:#078fc2;--accent-ink:#ffffff;--accent-soft:#dcf0fa;--accent-deep:#05668f;',
    '--accent:#6244a9;--accent-ink:#ffffff;--accent-soft:#ece6f8;--accent-deep:#47308a;')
out = out.replace('content="#078fc2"', 'content="#6244a9"')
out = out.replace('--accent:#33b4e4;--accent-ink:#04202d;--accent-soft:#113b50;--accent-deep:#7fd0ef;',
                  '--accent:#a98ef0;--accent-ink:#1b1036;--accent-soft:#2c2350;--accent-deep:#cdbdf7;')
out = out.replace('--bg:#0c1820;--surface:#12232e;--surface-2:#173040;--line:#23404f;',
                  '--bg:#110f1d;--surface:#1a1729;--surface-2:#241f38;--line:#332c4d;')
rep('</style>', '.hero{background:linear-gradient(125deg,#263c86,#6241a9 55%,#0a8b99);color:#fff}\n</style>')
for n in ('manifest.webmanifest?v=120', 'icon-192.png?v=120', 'icon-180.png?v=120'):
    rep(n, n.replace('?v=120', '?v=2'), 0)
i = out.index('function tutorSuggestions(s){return({'); j = out.index('})[s]||[]}', i)
out = out[:i] + "function tutorSuggestions(s){return(" + J({
    'general': ['كيف أذاكر قبل امتحانات الشهادة الإعدادية؟', 'حل: 2س + 3 = 11', 'ما علامة رفع الفاعل؟'],
    'arabic': ['ما علامة رفع الفاعل؟', 'اشرح كان وأخواتها'],
    'english': ['متى أستخدم present perfect؟', 'What is the past of "go"?'],
    'math': ['حل: 2س + 3 = 11', 'احسب مساحة مستطيل طوله 6 وعرضه 4'],
    'science': ['ما الفرق بين التغير الفيزيائي والكيميائي؟', 'احسب السرعة: 100 متر في 20 ثانية'],
    'social': ['في أي قارة تقع مصر؟', 'ما أهمية نهر النيل لمصر؟'],
}) + out[j+1:]
out = out.replace('\\nالمدرس الذكي الكامل يعمل عند فتح التطبيق داخل Claude.', '')
assert 'داخل Claude' not in out, 'Claude line left'
assert 'tafawoq_' not in out.replace('tafawoq_plus', '').replace('tafawoq_prep', ''), 'storage key left'

sw_out = sw.replace("const CACHE='tafawoq-", "const CACHE='tafawoqprep-").replace("x.startsWith('tafawoq-')", "x.startsWith('tafawoqprep-')").replace("'./icon.svg'", "'./icon-192.png'")
assert 'tafawoqprep-' in sw_out
os.makedirs(OUT, exist_ok=True)
open(os.path.join(OUT, 'index.html'), 'w', encoding='utf-8').write(out)
open(os.path.join(OUT, 'sw.js'), 'w', encoding='utf-8').write(sw_out)
print('built', len(out), {k: len(v) for k, v in bank.items()})
